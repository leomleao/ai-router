//! Pinned Cloud Code Assist wire conversion. No transport, credentials, or logging.
//!
//! Protocol provenance: oh-my-pi, MIT, commit
//! 2220e58146ebe31508e7a216242840d373e082d0, packages/ai/src/providers/
//! google-gemini-cli.ts and google-shared.ts, plus packages/catalog/src/wire/
//! gemini-headers.ts. See THIRD_PARTY_NOTICES.md for the upstream notice.
//! Visible text is preserved. Tool schemas use CCA-compatible provider hints;
//! the original JSON Schema remains authoritative for local handoff validation.
use crate::protocol::{ApiError, RunRequest, ToolCall, Usage};
use serde_json::{Value, json};
use sha2::{Digest, Sha256};
use std::collections::{HashMap, HashSet};

const MAX_ITEMS: usize = 4096;
const MAX_TOOLS: usize = 128;
const MAX_FRAME_BYTES: usize = 1024 * 1024;
const MAX_STREAM_BYTES: usize = 64 * 1024 * 1024;
const MAX_OUTPUT_BYTES: usize = 16 * 1024 * 1024;

fn invalid(code: &'static str) -> ApiError {
    let mut error = ApiError::new(
        502,
        code,
        "Antigravity returned an invalid or unsupported response",
    );
    error.diagnostics = Some(crate::protocol::FailureDiagnostics::metadata(
        json!({"phase":"wire_validation","reason":code}),
    ));
    error
}
fn invalid_tool(reason: &'static str) -> ApiError {
    let mut error = invalid("invalid_provider_tool_call");
    error.diagnostics = Some(crate::protocol::FailureDiagnostics::metadata(
        json!({"phase":"tool_validation","reason":reason}),
    ));
    error
}

fn text_content(value: &Value) -> Result<String, ApiError> {
    if value.is_null() {
        return Ok(String::new());
    }
    if let Some(text) = value.as_str() {
        return Ok(text.to_owned());
    }
    let mut out = String::new();
    for part in value
        .as_array()
        .ok_or_else(|| ApiError::unsupported("non-text input"))?
    {
        if !matches!(
            part["type"].as_str(),
            Some("text" | "input_text" | "output_text")
        ) {
            return Err(ApiError::unsupported("non-text input"));
        }
        out.push_str(
            part["text"]
                .as_str()
                .ok_or_else(|| ApiError::bad_request("Invalid text input"))?,
        );
    }
    Ok(out)
}

fn history_call(value: &Value, responses: bool) -> Result<ToolCall, ApiError> {
    let id = value[if responses { "call_id" } else { "id" }]
        .as_str()
        .filter(|v| valid_id(v))
        .ok_or_else(|| ApiError::bad_request("Invalid tool-call ID"))?;
    let function = if responses { value } else { &value["function"] };
    let name = function["name"]
        .as_str()
        .ok_or_else(|| ApiError::bad_request("Invalid tool name"))?;
    let arguments = serde_json::from_str::<Value>(function["arguments"].as_str().unwrap_or(""))
        .map_err(|_| ApiError::bad_request("Invalid tool arguments in history"))?;
    if !arguments.is_object() {
        return Err(ApiError::bad_request(
            "Tool arguments in history must be an object",
        ));
    }
    Ok(ToolCall {
        id: id.to_owned(),
        name: name.to_owned(),
        arguments,
    })
}

fn valid_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 256 && id.bytes().all(|b| b.is_ascii_graphic())
}

fn call_part(call: &ToolCall) -> Value {
    json!({"functionCall":{"id":call.id,"name":call.name,"args":call.arguments}})
}

fn public_calls(parts: &[Value]) -> Vec<Value> {
    parts
        .iter()
        .filter_map(|part| part.get("functionCall"))
        .map(|call| json!({"id":call["id"],"name":call["name"],"arguments":call["args"]}))
        .collect()
}

fn public_text(parts: &[Value]) -> String {
    parts
        .iter()
        .filter(|part| part["thought"] != true)
        .filter_map(|part| part["text"].as_str())
        .collect()
}

/// Trusted replay entries are generated by `Decoder` and must be scoped by the
/// caller to owner, exact model, account and generation. Never pass client JSON
/// as replay. Entries match complete public turns; ambiguity fails closed.
fn restore_parts(
    parts: &mut Vec<Value>,
    replay: &[Value],
    used: &mut HashSet<usize>,
    prefix: &[Value],
    system: &[Value],
) -> Result<(), ApiError> {
    let text = public_text(parts);
    let calls = public_calls(parts);
    let anchor = anchor(prefix, system);
    let matches: Vec<_> = replay
        .iter()
        .enumerate()
        .filter(|(index, entry)| {
            !used.contains(index)
                && entry["anchor"] == anchor
                && entry["text"] == text
                && entry["tool_calls"] == json!(calls)
        })
        .collect();
    if matches.len() > 1 {
        return Err(ApiError::bad_request(
            "Ambiguous Antigravity conversation replay",
        ));
    }
    if let Some((index, entry)) = matches.first() {
        let restored = entry["parts"]
            .as_array()
            .ok_or_else(|| ApiError::internal("Invalid private replay state"))?;
        if restored.len() > MAX_ITEMS
            || public_text(restored) != text
            || public_calls(restored) != calls
        {
            return Err(ApiError::internal("Invalid private replay state"));
        }
        *parts = restored.clone();
        used.insert(*index);
    }
    Ok(())
}

fn anchor(contents: &[Value], system: &[Value]) -> Value {
    // The public APIs group assistant text and calls differently and discard
    // thought parts. Canonicalize that same public representation, without
    // moving private reasoning between history branches or exposing its hash.
    let contents: Vec<Value> = contents.iter().map(|content| {
        let parts = content["parts"].as_array().map(Vec::as_slice).unwrap_or(&[]);
        let mut canonical = Vec::new();
        let text = public_text(parts);
        if !text.is_empty() { canonical.push(json!({"text":text})); }
        for part in parts {
            if let Some(call) = part.get("functionCall") {
                canonical.push(json!({"functionCall":{"name":call["name"],"args":call["args"]}}));
            }
            if let Some(response) = part.get("functionResponse") {
                canonical.push(json!({"functionResponse":{"name":response["name"],"response":response["response"]}}));
            }
        }
        json!({"role":content["role"],"parts":canonical})
    }).collect();
    let bytes =
        serde_json::to_vec(&json!({"contents":contents,"system":system})).unwrap_or_default();
    json!(format!("{:x}", Sha256::digest(bytes)))
}

/// Anchor a just-serialized request before storing its generated private replay
/// entry. This binds replay to its full public history and instruction branch.
pub fn request_anchor(body: &Value) -> Value {
    let contents = body
        .pointer("/request/contents")
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or(&[]);
    let system = body
        .pointer("/request/systemInstruction/parts")
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or(&[]);
    anchor(contents, system)
}

fn session_id(request: &RunRequest) -> Result<String, ApiError> {
    if let Some(first_user) = request.input.iter().find(|item| item["role"] == "user") {
        let text = text_content(&first_user["content"])?;
        if !text.trim().is_empty() {
            // OMP's stateless fallback derives a stable negative decimal from
            // the first user's text. Scope that derivation to this router's
            // owner/model/account generation, without sending those identifiers.
            let encoded = serde_json::to_vec(&json!([
                request.owner,
                request.model,
                request.provider_generation,
                text
            ]))
            .map_err(|_| ApiError::internal("Could not encode Antigravity session scope"))?;
            let digest = Sha256::digest(encoded);
            let mut bytes = [0u8; 8];
            bytes.copy_from_slice(&digest[..8]);
            return Ok(format!(
                "-{}",
                u64::from_be_bytes(bytes) & (i64::MAX as u64)
            ));
        }
    }
    // Match the pinned protocol's bounded negative fallback when history does
    // not contain a nonempty first user turn.
    loop {
        let value = rand::random::<u64>() & (i64::MAX as u64);
        if value < 9_000_000_000_000_000_000 {
            return Ok(format!("-{value}"));
        }
    }
}

/// Serialize normalized typed history, never the CLI's rendered transcript.
/// Current exact wire IDs encode effort; matching explicit effort is redundant,
/// while a conflict is rejected rather than silently selecting another tier.
pub fn serialize(request: &RunRequest, project: &str, replay: &[Value]) -> Result<Value, ApiError> {
    if project.is_empty()
        || project.len() > 256
        || !project
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.' | b':'))
    {
        return Err(ApiError::bad_request("Invalid Antigravity project"));
    }
    if let Some(effort) = &request.effort {
        if request.model.rsplit('-').next() != Some(effort.as_str()) {
            return Err(ApiError::bad_request(
                "reasoning_effort conflicts with the exact model ID",
            ));
        }
    }
    if request.input.len() > 1000 || request.instructions.len() > 1000 || replay.len() > MAX_ITEMS {
        return Err(ApiError::bad_request(
            "Antigravity conversation exceeds item limits",
        ));
    }
    let mut system = Vec::new();
    for instruction in &request.instructions {
        system.push(json!({"text":text_content(&instruction["content"])?}));
    }
    if let Some(schema) = &request.schema {
        crate::protocol::validate_schema(schema)?;
        // Local post-validation remains authoritative. CCA's native schema
        // dialect is narrower than accepted JSON Schema; do not erase keywords.
        system.push(json!({"text":format!("Return only one JSON value matching this JSON Schema: {}", schema)}));
    }
    let mut contents: Vec<Value> = Vec::new();
    let mut calls: HashMap<String, (String, usize)> = HashMap::new();
    let mut returned = HashSet::new();
    let mut used_replay = HashSet::new();
    let mut index = 0;
    while index < request.input.len() {
        let item = &request.input[index];
        match item["type"].as_str().unwrap_or("message") {
            "message" => {
                let role = item["role"]
                    .as_str()
                    .ok_or_else(|| ApiError::bad_request("Invalid history role"))?;
                if matches!(role, "system" | "developer") {
                    // A system change in the middle cannot be represented as a
                    // global systemInstruction without changing chronology.
                    return Err(ApiError::unsupported(
                        "mid-conversation system/developer messages",
                    ));
                }
                if role == "tool" {
                    let start = index;
                    let mut results = Vec::new();
                    while index < request.input.len() && request.input[index]["role"] == "tool" {
                        let result = &request.input[index];
                        let id = result["tool_call_id"]
                            .as_str()
                            .ok_or_else(|| ApiError::bad_request("Invalid tool result"))?;
                        let (name, order) = calls
                            .get(id)
                            .ok_or_else(|| ApiError::bad_request("Unknown tool result"))?;
                        if !returned.insert(id.to_owned()) {
                            return Err(ApiError::bad_request("Duplicate tool result"));
                        }
                        results.push((*order, json!({"functionResponse":{"id":id,"name":name,"response":{"output":text_content(&result["content"])?}}})));
                        index += 1;
                    }
                    if index == start {
                        return Err(ApiError::internal("Invalid tool result conversion"));
                    }
                    results.sort_by_key(|(order, _)| *order);
                    contents.push(json!({"role":"user","parts":results.into_iter().map(|(_,v)|v).collect::<Vec<_>>()}));
                    continue;
                }
                if !matches!(role, "user" | "assistant") {
                    return Err(ApiError::unsupported("history role"));
                }
                let text = text_content(&item["content"])?;
                let mut parts = Vec::new();
                if !text.is_empty() {
                    parts.push(json!({"text":text}));
                }
                if let Some(history_calls) = item.get("tool_calls").filter(|v| !v.is_null()) {
                    if role != "assistant" {
                        return Err(ApiError::bad_request("Invalid tool-call history"));
                    }
                    for value in history_calls
                        .as_array()
                        .ok_or_else(|| ApiError::bad_request("Invalid tool-call history"))?
                    {
                        let call = history_call(value, false)?;
                        let ordinal = calls.len();
                        if calls
                            .insert(call.id.clone(), (call.name.clone(), ordinal))
                            .is_some()
                        {
                            return Err(ApiError::bad_request("Duplicate tool-call ID"));
                        }
                        parts.push(call_part(&call));
                    }
                }
                if role == "assistant" {
                    // Responses stores text and function calls as separate
                    // adjacent items, but they form a single model wire turn.
                    while request
                        .input
                        .get(index + 1)
                        .is_some_and(|v| v["type"] == "function_call")
                    {
                        index += 1;
                        let call = history_call(&request.input[index], true)?;
                        let ordinal = calls.len();
                        if calls
                            .insert(call.id.clone(), (call.name.clone(), ordinal))
                            .is_some()
                        {
                            return Err(ApiError::bad_request("Duplicate tool-call ID"));
                        }
                        parts.push(call_part(&call));
                    }
                    restore_parts(&mut parts, replay, &mut used_replay, &contents, &system)?;
                }
                if !parts.is_empty() {
                    contents.push(
                        json!({"role":if role=="assistant" {"model"} else {"user"},"parts":parts}),
                    );
                }
            }
            "function_call" => {
                let mut parts = Vec::new();
                loop {
                    let call = history_call(&request.input[index], true)?;
                    let ordinal = calls.len();
                    if calls
                        .insert(call.id.clone(), (call.name.clone(), ordinal))
                        .is_some()
                    {
                        return Err(ApiError::bad_request("Duplicate tool-call ID"));
                    }
                    parts.push(call_part(&call));
                    if !request
                        .input
                        .get(index + 1)
                        .is_some_and(|v| v["type"] == "function_call")
                    {
                        break;
                    }
                    index += 1;
                }
                restore_parts(&mut parts, replay, &mut used_replay, &contents, &system)?;
                contents.push(json!({"role":"model","parts":parts}));
            }
            "function_call_output" => {
                let mut results = Vec::new();
                loop {
                    let result = &request.input[index];
                    let id = result["call_id"]
                        .as_str()
                        .ok_or_else(|| ApiError::bad_request("Invalid tool result"))?;
                    let (name, order) = calls
                        .get(id)
                        .ok_or_else(|| ApiError::bad_request("Unknown tool result"))?;
                    if !returned.insert(id.to_owned()) {
                        return Err(ApiError::bad_request("Duplicate tool result"));
                    }
                    results.push((*order, json!({"functionResponse":{"id":id,"name":name,"response":{"output":text_content(&result["output"])?}}})));
                    if !request
                        .input
                        .get(index + 1)
                        .is_some_and(|v| v["type"] == "function_call_output")
                    {
                        break;
                    }
                    index += 1;
                }
                results.sort_by_key(|(order, _)| *order);
                contents.push(json!({"role":"user","parts":results.into_iter().map(|(_,v)|v).collect::<Vec<_>>()}));
            }
            "reasoning" => {
                return Err(ApiError::unsupported(
                    "reasoning items from another provider",
                ));
            }
            _ => return Err(ApiError::unsupported("history item type")),
        }
        index += 1;
    }
    if contents.is_empty() {
        return Err(ApiError::bad_request(
            "At least one conversation turn is required",
        ));
    }
    // CCA requires one complete, contiguous response group following each
    // model call group. Never match an unrelated result by its array position.
    for (index, content) in contents.iter().enumerate() {
        let parts = content["parts"]
            .as_array()
            .ok_or_else(|| ApiError::internal("Invalid conversation conversion"))?;
        let expected: Vec<_> = parts
            .iter()
            .filter_map(|part| part.pointer("/functionCall/id").and_then(Value::as_str))
            .collect();
        let responses: Vec<_> = parts
            .iter()
            .filter_map(|part| part.pointer("/functionResponse/id").and_then(Value::as_str))
            .collect();
        if !expected.is_empty() {
            let next = contents
                .get(index + 1)
                .and_then(|v| v["parts"].as_array())
                .ok_or_else(|| {
                    ApiError::bad_request("Tool calls require a complete following result group")
                })?;
            let actual: Vec<_> = next
                .iter()
                .filter_map(|part| part.pointer("/functionResponse/id").and_then(Value::as_str))
                .collect();
            if expected != actual {
                return Err(ApiError::bad_request(
                    "Tool results must completely match the preceding call group",
                ));
            }
        }
        if !responses.is_empty()
            && (index == 0
                || !contents[index - 1]["parts"]
                    .as_array()
                    .is_some_and(|parts| {
                        parts.iter().any(|part| part.get("functionCall").is_some())
                    }))
        {
            return Err(ApiError::bad_request(
                "Tool results require a preceding call group",
            ));
        }
    }
    // All current IDs are absent from OMP's observed fixed-profile table. In
    // particular, do not guess a numeric thinking budget or output ceiling.
    // Pinned CCA model compat differs by family: Claude supports function-part
    // IDs, while Gemini uses ordered groups without wire IDs. Claude also
    // rejects unsigned thinking on replay. Preserve client IDs internally.
    let claude_model = request.model.starts_with("claude-");
    for content in &mut contents {
        let mut first_call = true;
        if let Some(parts) = content["parts"].as_array_mut() {
            // A standalone empty visible text/signature part has no public
            // content. CCA omits the proto's zero-valued text and Claude then
            // receives an invalid text block with a missing text field. Keep
            // this metadata private, but do not send that empty visible part.
            // Typed signature-only thoughts remain provider replay state.
            parts.retain(|part| part["thought"] == true || part["text"] != "");
            if claude_model {
                parts.retain(|part| {
                    part["thought"] != true
                        || part["thoughtSignature"]
                            .as_str()
                            .is_some_and(|value| !value.is_empty())
                });
            }
            for part in parts {
                if let Some(call) = part.get_mut("functionCall").and_then(Value::as_object_mut) {
                    if !claude_model {
                        call.remove("id");
                    }
                    if first_call
                        && request.model.starts_with("gemini-")
                        && part["thoughtSignature"].as_str().is_none_or(str::is_empty)
                    {
                        part["thoughtSignature"] = json!("skip_thought_signature_validator");
                    }
                    first_call = false;
                }
                if let Some(response) = part
                    .get_mut("functionResponse")
                    .and_then(Value::as_object_mut)
                {
                    if !claude_model {
                        response.remove("id");
                    }
                }
            }
        }
    }
    let trajectory = uuid::Uuid::new_v4().to_string();
    let agent = uuid::Uuid::new_v4().to_string();
    let session = session_id(request)?;
    let claude = request.model.starts_with("claude-").to_string();
    let mut body = json!({"contents":contents,"sessionId":session,"labels":{
        "last_step_index":"1","trajectory_id":trajectory,"used_claude":claude,"used_claude_conservative":claude
    }});
    if !system.is_empty() {
        body["systemInstruction"] = json!({"role":"user","parts":system});
    }
    if matches!(
        request.model.as_str(),
        "claude-opus-5-5-low"
            | "claude-opus-5-5-medium"
            | "claude-opus-5-5-high"
            | "claude-sonnet-5-5-low"
            | "claude-sonnet-5-5-medium"
            | "claude-sonnet-5-5-high"
    ) {
        // Request the private thought/signature parts needed for faithful
        // continuation. Exact wire IDs retain their own reasoning tier; this
        // flag neither invents a numeric budget nor changes effort.
        body["generationConfig"] = json!({"thinkingConfig":{"includeThoughts":true}});
    }
    if !request.tools.is_empty() {
        if request.tools.len() > MAX_TOOLS {
            return Err(ApiError::bad_request("Too many tools"));
        }
        let mut names = HashSet::new();
        let mut declarations = Vec::new();
        for tool in &request.tools {
            crate::protocol::validate_schema(&tool.parameters)?;
            if !names.insert(&tool.name) {
                return Err(ApiError::bad_request("Duplicate tool definition"));
            }
            let parameters = crate::antigravity_schema::parameters(&tool.parameters);
            let description = if parameters != tool.parameters {
                format!(
                    "{}\nClient argument contract (JSON Schema; all constraints apply):\n{}",
                    tool.description, tool.parameters
                )
            } else {
                tool.description.clone()
            };
            declarations
                .push(json!({"name":tool.name,"description":description,"parameters":parameters}));
        }
        body["tools"] = json!([{"functionDeclarations":declarations}]);
        body["toolConfig"] = json!({"functionCallingConfig":{"mode":"VALIDATED"}});
    } else if request.model.starts_with("claude-") {
        body["toolConfig"] = json!({"functionCallingConfig":{"mode":"VALIDATED"}});
    }
    let envelope = json!({"project":project,"model":request.model,"request":body,
        "requestId":format!("agent/{agent}/{}/{trajectory}/2",chrono::Utc::now().timestamp_millis()),
        "userAgent":"antigravity","requestType":"agent"});
    if serde_json::to_vec(&envelope).map_or(true, |v| v.len() > MAX_OUTPUT_BYTES) {
        return Err(ApiError::bad_request(
            "Antigravity request exceeds byte limits",
        ));
    }
    Ok(envelope)
}

/// Private replay is intentionally not Debug/Serialize: it can contain opaque
/// signatures and private thought text. Only public fields enter RunResult.
pub struct Decoded {
    pub text: String,
    pub tool_calls: Vec<ToolCall>,
    pub usage: Option<Usage>,
    pub usage_partial: bool,
    pub status: String,
    pub replay: Vec<Value>,
    pub upstream_request_id: Option<String>,
}

pub struct Decoder {
    request: RunRequest,
    buffer: Vec<u8>,
    data: Vec<u8>,
    has_data: bool,
    pending_cr: bool,
    event_error: bool,
    bytes: usize,
    max_bytes: usize,
    parts: Vec<Value>,
    text: String,
    calls: Vec<ToolCall>,
    call_ids: HashSet<String>,
    finish_reason: Option<String>,
    done: bool,
    failed: bool,
    usage: Option<Usage>,
    usage_partial: bool,
    upstream_request_id: Option<String>,
    frames: usize,
}

impl Decoder {
    pub fn new(request: &RunRequest, max_bytes: usize) -> Self {
        Self {
            request: request.clone(),
            buffer: Vec::new(),
            data: Vec::new(),
            has_data: false,
            pending_cr: false,
            event_error: false,
            bytes: 0,
            max_bytes: max_bytes.min(MAX_STREAM_BYTES),
            parts: Vec::new(),
            text: String::new(),
            calls: Vec::new(),
            call_ids: HashSet::new(),
            finish_reason: None,
            done: false,
            failed: false,
            usage: None,
            usage_partial: true,
            upstream_request_id: None,
            frames: 0,
        }
    }

    /// Visible text only; tool calls are held until a validated terminal.
    /// A failed decoder is permanently poisoned to prevent partial reuse.
    pub fn push(&mut self, chunk: &[u8]) -> Result<Vec<String>, ApiError> {
        if self.failed {
            return Err(invalid("invalid_provider_stream"));
        }
        let result = self.push_inner(chunk).map_err(|mut error| {
            error.upstream_request_id = self.upstream_request_id.clone();
            error
        });
        if result.is_err() {
            self.failed = true;
        }
        result
    }

    fn push_inner(&mut self, chunk: &[u8]) -> Result<Vec<String>, ApiError> {
        self.bytes = self
            .bytes
            .checked_add(chunk.len())
            .ok_or_else(|| invalid("provider_output_limit"))?;
        if self.bytes > self.max_bytes {
            return Err(invalid("provider_output_limit"));
        }
        self.buffer.extend_from_slice(chunk);
        let mut deltas = Vec::new();
        let mut consumed = 0;
        while consumed < self.buffer.len() {
            if self.pending_cr {
                self.pending_cr = false;
                if self.buffer[consumed] == b'\n' {
                    consumed += 1;
                    continue;
                }
            }
            let Some(relative_end) = self.buffer[consumed..]
                .iter()
                .position(|b| matches!(*b, b'\n' | b'\r'))
            else {
                break;
            };
            let end = consumed + relative_end;
            let line = self.buffer[consumed..end].to_vec();
            self.pending_cr = self.buffer[end] == b'\r';
            consumed = end + 1;
            if line.len() > MAX_FRAME_BYTES {
                return Err(invalid("provider_frame_limit"));
            }
            // Every complete line must be UTF-8; the unfinished line can end
            // in the middle of a multibyte code point until the next chunk.
            let line = std::str::from_utf8(&line).map_err(|_| invalid("invalid_provider_utf8"))?;
            if line.is_empty() {
                if self.event_error {
                    return Err(invalid("provider_stream_error"));
                }
                if self.has_data {
                    let data = std::mem::take(&mut self.data);
                    self.has_data = false;
                    self.frame(&data, &mut deltas)?;
                }
                self.event_error = false;
            } else if line.starts_with(':') {
                continue;
            } else {
                let (field, value) = line.split_once(':').unwrap_or((line, ""));
                let value = value.strip_prefix(' ').unwrap_or(value);
                match field {
                    "data" => {
                        if self.has_data {
                            self.data.push(b'\n');
                        }
                        self.has_data = true;
                        if self.data.len().saturating_add(value.len()) > MAX_FRAME_BYTES {
                            return Err(invalid("provider_frame_limit"));
                        }
                        self.data.extend_from_slice(value.as_bytes());
                    }
                    "event" => {
                        if value == "error" {
                            self.event_error = true;
                        } else if !matches!(value, "" | "message") {
                            return Err(invalid("unsupported_provider_event"));
                        }
                    }
                    "id" | "retry" => {}
                    _ => return Err(invalid("unsupported_provider_event")),
                }
            }
        }
        self.buffer.drain(..consumed);
        if self.buffer.len().saturating_add(self.data.len()) > MAX_FRAME_BYTES {
            return Err(invalid("provider_frame_limit"));
        }
        Ok(deltas)
    }

    fn frame(&mut self, data: &[u8], deltas: &mut Vec<String>) -> Result<(), ApiError> {
        self.frames += 1;
        if self.frames > MAX_ITEMS * 4 {
            return Err(invalid("provider_event_limit"));
        }
        if data == b"[DONE]" {
            if self.done || self.finish_reason.is_none() {
                return Err(invalid("invalid_provider_terminal"));
            }
            self.done = true;
            return Ok(());
        }
        if self.done {
            return Err(invalid("invalid_provider_terminal"));
        }
        let value: Value =
            serde_json::from_slice(data).map_err(|_| invalid("invalid_provider_json"))?;
        if value.get("error").is_some() {
            return Err(stream_error(&value["error"]));
        }
        let response = value
            .get("response")
            .filter(|v| v.is_object())
            .ok_or_else(|| invalid("invalid_provider_envelope"))?;
        if response.get("error").is_some() {
            return Err(stream_error(&response["error"]));
        }
        if let Some(id) = response.get("responseId") {
            let id = id
                .as_str()
                .filter(|id| valid_id(id))
                .ok_or_else(|| invalid("invalid_provider_request_id"))?;
            if self
                .upstream_request_id
                .as_ref()
                .is_some_and(|previous| previous != id)
            {
                return Err(invalid("conflicting_provider_request_id"));
            }
            self.upstream_request_id = Some(id.to_owned());
        }
        if response.pointer("/promptFeedback/blockReason").is_some() {
            return Err(invalid("provider_content_blocked"));
        }
        if let Some(candidates) = response.get("candidates") {
            let candidates = candidates
                .as_array()
                .ok_or_else(|| invalid("invalid_provider_candidate"))?;
            if candidates.len() > 1 {
                return Err(invalid("unsupported_provider_candidates"));
            }
            if let Some(candidate) = candidates.first() {
                if candidate.get("index").is_some_and(|v| v != 0) {
                    return Err(invalid("invalid_provider_candidate"));
                }
                if let Some(content) = candidate.get("content") {
                    if content.get("role").is_some_and(|v| v != "model") {
                        return Err(invalid("invalid_provider_role"));
                    }
                    let parts = content["parts"]
                        .as_array()
                        .ok_or_else(|| invalid("invalid_provider_parts"))?;
                    if self.finish_reason.is_some() && !parts.is_empty() {
                        return Err(invalid("content_after_provider_terminal"));
                    }
                    for part in parts {
                        self.part(part, deltas)?;
                    }
                }
                if let Some(reason) = candidate.get("finishReason") {
                    let reason = reason
                        .as_str()
                        .ok_or_else(|| invalid("invalid_provider_terminal"))?;
                    if self.finish_reason.is_some() {
                        return Err(invalid("duplicate_provider_terminal"));
                    }
                    match reason {
                        "STOP" | "MAX_TOKENS" => self.finish_reason = Some(reason.to_owned()),
                        "SAFETY" | "RECITATION" | "BLOCKLIST" | "PROHIBITED_CONTENT" | "SPII"
                        | "IMAGE_SAFETY" => return Err(invalid("provider_content_blocked")),
                        _ => return Err(invalid("invalid_provider_terminal")),
                    }
                }
            }
        }
        if let Some(metadata) = response.get("usageMetadata") {
            let (usage, partial) = usage(metadata)?;
            self.usage = Some(usage);
            self.usage_partial = partial;
        }
        Ok(())
    }

    fn part(&mut self, part: &Value, deltas: &mut Vec<String>) -> Result<(), ApiError> {
        let object = part
            .as_object()
            .ok_or_else(|| invalid("invalid_provider_part"))?;
        if object.keys().any(|key| {
            !matches!(
                key.as_str(),
                "text" | "thought" | "thoughtSignature" | "functionCall"
            )
        }) {
            return Err(invalid("unsupported_provider_part"));
        }
        if self.parts.len() >= MAX_ITEMS {
            return Err(invalid("provider_item_limit"));
        }
        if part.get("thought").is_some_and(|v| !v.is_boolean())
            || part.get("thoughtSignature").is_some_and(|v| !v.is_string())
        {
            return Err(invalid("invalid_provider_part"));
        }
        let mut retained = part.clone();
        if let Some(call) = part.get("functionCall") {
            if part["thought"] == true || part.get("text").is_some_and(|v| v != "") {
                return Err(invalid_tool("conflicting_function_part"));
            }
            if self.calls.len() >= MAX_TOOLS {
                return Err(invalid("provider_tool_limit"));
            }
            let call_object = call
                .as_object()
                .ok_or_else(|| invalid_tool("function_call_not_object"))?;
            if call_object
                .keys()
                .any(|key| !matches!(key.as_str(), "id" | "name" | "args"))
            {
                return Err(invalid_tool("unexpected_function_call_fields"));
            }
            let arguments = call.get("args").cloned().unwrap_or_else(|| json!({}));
            crate::tool_diagnostics::validate_call(
                &self.request.tools,
                call.get("name"),
                &arguments,
            )
            .map_err(|rejection| {
                let mut error = invalid("invalid_provider_tool_call");
                error.diagnostics = Some(crate::protocol::FailureDiagnostics::metadata(
                    json!({"phase":"tool_validation","validation":rejection}),
                ));
                error
            })?;
            let name = call["name"].as_str().expect("validated client tool name");
            let id = if let Some(id) = call.get("id") {
                id.as_str()
                    .filter(|id| valid_id(id))
                    .ok_or_else(|| invalid_tool("invalid_function_call_id"))?
                    .to_owned()
            } else {
                format!("call_{}", uuid::Uuid::new_v4().simple())
            };
            if !self.call_ids.insert(id.clone()) {
                return Err(invalid("duplicate_provider_tool_call"));
            }
            // Part text/functionCall are alternative payloads. An upstream
            // response may include empty/default text fields, but replay must
            // not send both oneof payload keys, even when text is empty.
            retained = json!({"functionCall":{"id":id,"name":name,"args":arguments}});
            if let Some(signature) = part["thoughtSignature"]
                .as_str()
                .filter(|value| !value.is_empty())
            {
                retained["thoughtSignature"] = json!(signature);
            }
            self.calls.push(ToolCall {
                id,
                name: name.to_owned(),
                arguments,
            });
        } else if let Some(text) = part.get("text") {
            let text = text
                .as_str()
                .ok_or_else(|| invalid("invalid_provider_text"))?;
            if part["thought"] != true && !text.is_empty() {
                if self.text.len().saturating_add(text.len()) > MAX_OUTPUT_BYTES {
                    return Err(invalid("provider_output_limit"));
                }
                self.text.push_str(text);
                // A schema response is not public until complete validation by
                // the adapter; returning no deltas prevents accidental leakage.
                if self.request.schema.is_none() {
                    deltas.push(text.to_owned());
                }
            }
        } else if part.get("thoughtSignature").is_some() {
            // Signature-only empty thoughts remain typed private blocks.
            retained["text"] = json!("");
        } else {
            return Err(invalid("unsupported_provider_part"));
        }
        self.retain_part(retained);
        Ok(())
    }

    /// CCA sends deltas for a contiguous text/thought block; a signature may
    /// arrive on its first delta or in an empty trailing delta. Reassemble that
    /// same typed block so Claude does not lose signed thinking when dropping
    /// unsigned blocks on replay. Distinct nonempty signatures retain distinct
    /// parts rather than moving a signature onto another signed block.
    fn retain_part(&mut self, retained: Value) {
        if retained.get("functionCall").is_none() {
            if let Some(previous) = self
                .parts
                .last_mut()
                .filter(|part| part.get("functionCall").is_none())
            {
                let signature_only = retained["text"] == ""
                    && retained.get("thought").is_none()
                    && retained["thoughtSignature"]
                        .as_str()
                        .is_some_and(|signature| !signature.is_empty());
                let same_kind = (previous["thought"] == true) == (retained["thought"] == true);
                let previous_signature = previous["thoughtSignature"]
                    .as_str()
                    .filter(|signature| !signature.is_empty());
                let next_signature = retained["thoughtSignature"]
                    .as_str()
                    .filter(|signature| !signature.is_empty());
                let distinct_signatures =
                    matches!((previous_signature,next_signature),(Some(a),Some(b)) if a != b);
                if (same_kind || signature_only) && !distinct_signatures {
                    let mut text = previous["text"].as_str().unwrap_or("").to_owned();
                    text.push_str(retained["text"].as_str().unwrap_or(""));
                    previous["text"] = json!(text);
                    if next_signature.is_some() {
                        previous["thoughtSignature"] = retained["thoughtSignature"].clone();
                    }
                    return;
                }
            }
        }
        self.parts.push(retained);
    }

    pub fn finish(self) -> Result<Decoded, ApiError> {
        if self.failed || !self.buffer.is_empty() || self.has_data || self.event_error {
            return Err(invalid("truncated_provider_stream"));
        }
        let reason = self
            .finish_reason
            .as_deref()
            .ok_or_else(|| invalid("missing_provider_terminal"))?;
        if !self.request.parallel_tool_calls && self.calls.len() > 1 {
            return Err(invalid_tool("parallel_calls_disabled"));
        }
        let complete = reason == "STOP";
        if complete && self.text.is_empty() && self.calls.is_empty() {
            return Err(invalid("empty_provider_output"));
        }
        if let Some(schema) = &self.request.schema {
            if !complete || !self.calls.is_empty() {
                return Err(invalid("incomplete_structured_output"));
            }
            let value: Value = serde_json::from_str(&self.text)
                .map_err(|_| invalid("invalid_structured_output"))?;
            let validator = jsonschema::validator_for(schema)
                .map_err(|_| ApiError::internal("Invalid response schema"))?;
            if !validator.is_valid(&value) {
                return Err(invalid("invalid_structured_output"));
            }
        }
        let replay = if complete {
            vec![
                json!({"text":self.text,"tool_ids":self.calls.iter().map(|call| &call.id).collect::<Vec<_>>(),
            "tool_calls":self.calls,"parts":self.parts}),
            ]
        } else {
            Vec::new()
        };
        Ok(Decoded {
            text: self.text,
            tool_calls: if complete { self.calls } else { Vec::new() },
            usage: self.usage,
            usage_partial: self.usage_partial || !complete,
            status: if complete { "completed" } else { "incomplete" }.to_owned(),
            replay,
            upstream_request_id: self.upstream_request_id,
        })
    }
}

fn stream_error(value: &Value) -> ApiError {
    let status = value["code"]
        .as_u64()
        .unwrap_or_else(|| match value["status"].as_str() {
            Some("UNAUTHENTICATED") => 401,
            Some("PERMISSION_DENIED") => 403,
            Some("RESOURCE_EXHAUSTED") => 429,
            _ => 502,
        });
    let mut error = match status {
        401 => ApiError::new(
            401,
            "provider_authentication_failed",
            "Antigravity authentication was rejected",
        ),
        403 => ApiError::new(
            403,
            "provider_account_restricted",
            "Antigravity denied this account",
        ),
        429 => ApiError::new(
            429,
            "provider_rate_limited",
            "Antigravity rate or quota limit reached",
        ),
        500..=599 => ApiError::new(
            502,
            "provider_upstream_error",
            "Antigravity returned an upstream error",
        ),
        _ => invalid("provider_stream_error"),
    };
    error.diagnostics = Some(crate::protocol::FailureDiagnostics::metadata(json!({
        "phase":"sse_error","provider_code":status,
    })));
    error
}

fn usage(metadata: &Value) -> Result<(Usage, bool), ApiError> {
    if !metadata.is_object() {
        return Err(invalid("invalid_provider_usage"));
    }
    let read = |key: &str| -> Result<Option<u64>, ApiError> {
        metadata
            .get(key)
            .map(|v| v.as_u64().ok_or_else(|| invalid("invalid_provider_usage")))
            .transpose()
    };
    let prompt = read("promptTokenCount")?;
    let candidates = read("candidatesTokenCount")?;
    let thoughts = read("thoughtsTokenCount")?;
    let total = read("totalTokenCount")?;
    let cache = read("cachedContentTokenCount")?;
    let output = candidates
        .unwrap_or(0)
        .checked_add(thoughts.unwrap_or(0))
        .ok_or_else(|| invalid("invalid_provider_usage"))?;
    let input = prompt.unwrap_or_else(|| total.unwrap_or(0).saturating_sub(output));
    let inferred_total = input
        .checked_add(output)
        .ok_or_else(|| invalid("invalid_provider_usage"))?;
    let partial = prompt.is_none()
        || candidates.is_none()
        || total.is_none()
        || total.is_some_and(|value| value != inferred_total)
        || cache.is_some_and(|value| value > input);
    // Public input includes cached input; output includes reasoning. Detail
    // counters are subsets and must not be added again to displayed totals.
    Ok((
        Usage {
            input_tokens: input,
            output_tokens: output,
            thinking_tokens: thoughts.unwrap_or(0),
            cache_read_tokens: cache.unwrap_or(0).min(input),
            total_tokens: total.unwrap_or(inferred_total),
        },
        partial,
    ))
}

